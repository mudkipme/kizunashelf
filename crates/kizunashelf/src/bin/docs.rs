// --- External providers ---------------------------------------------------------

fn providers_page() -> String {
    let catalog = provider_catalog_items();
    let episode_support: BTreeMap<&str, bool> = provider_episode_support().into_iter().collect();

    let mut out = String::new();
    front_matter(
        &mut out,
        "External providers",
        "Every external metadata provider, its credentials, searchable types, and mappable fields — generated from the provider registry.",
        9,
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "{BANNER}");
    let _ = writeln!(out);
    let _ = writeln!(out, "Generated directly from the app's provider catalog — the same one that powers matching, Quick Capture, and the Settings credential editors — so it always matches the version you're running. A provider is wired into a type through an `externalRef` field (and optionally `externalFields` / external body sections); see [External Metadata](./external.md#external-metadata).");
    let _ = writeln!(out);
    let _ = writeln!(out, "On self-hosted web, credentials come from the listed `KIZUNASHELF_*` environment variables; on desktop use **Settings → Provider Credentials**, and on iOS use **More → Provider Credentials**. Both store credentials in the OS keychain.");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "| Provider | `externalRef` id | Search | Episode/track sync | Credentials |"
    );
    let _ = writeln!(out, "| --- | --- | --- | --- | --- |");
    for item in &catalog {
        let search = if item.search_supported {
            "search + resolve"
        } else {
            "resolve URL/id only"
        };
        let episodes = if episode_support
            .get(item.id.as_str())
            .copied()
            .unwrap_or(false)
        {
            "yes"
        } else {
            "—"
        };
        let credentials = if item.credentials.is_empty() {
            "none".to_string()
        } else {
            item.credentials
                .iter()
                .map(|credential| {
                    let optional =
                        if credential.required || credential.label.ends_with(" (optional)") {
                            ""
                        } else {
                            " (optional)"
                        };
                    format!("{}{optional}", cell(&credential.label))
                })
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(
            out,
            "| [{label}](#{anchor}) | `{id}` | {search} | {episodes} | {credentials} |",
            label = cell(&item.label),
            anchor = item.id,
            id = item.id,
        );
    }
    let _ = writeln!(out);

    for item in &catalog {
        // Explicit anchor: heading text is the human label, but links and the
        // summary table key off the stable provider id.
        let _ = writeln!(out, "## {} {{#{}}}", cell(&item.label), item.id);
        let _ = writeln!(out);
        let search = if item.search_supported {
            "Supports free-text search and resolving a pasted URL/id."
        } else {
            "Resolves a pasted URL/id only — free-text search returns nothing."
        };
        let episodes = if episode_support
            .get(item.id.as_str())
            .copied()
            .unwrap_or(false)
        {
            " Can pull an episode/track list into an entity's episodes body section."
        } else {
            ""
        };
        let _ = writeln!(out, "`externalRef: {}` — {search}{episodes}", item.id);
        let _ = writeln!(out);

        if !item.credentials.is_empty() {
            let _ = writeln!(out, "| Credential | Key | Env var (web) | Required |");
            let _ = writeln!(out, "| --- | --- | --- | --- |");
            for credential in &item.credentials {
                let _ = writeln!(
                    out,
                    "| {label} | `{key}` | `{env}` | {required} |",
                    label = cell(&credential.label),
                    key = credential.key,
                    env = credential_env_var(&credential.key),
                    required = if credential.required {
                        "required"
                    } else {
                        "optional"
                    },
                );
            }
            let _ = writeln!(out);
        }

        if !item.types.is_empty() {
            let _ = writeln!(out, "`externalTypes` values (defaults marked ✓):");
            let _ = writeln!(out);
            let _ = writeln!(out, "| Value | Meaning | Default |");
            let _ = writeln!(out, "| --- | --- | --- |");
            for type_option in &item.types {
                let default = if item.default_external_types.contains(&type_option.value) {
                    "✓"
                } else {
                    ""
                };
                let _ = writeln!(
                    out,
                    "| `{value}` | {label} | {default} |",
                    value = cell(&type_option.value),
                    label = cell(&type_option.label),
                );
            }
            let _ = writeln!(out);
        }

        if !item.fields.is_empty() {
            let _ = writeln!(
                out,
                "Mappable fields (for `externalFields` and external body sections):"
            );
            let _ = writeln!(out);
            let _ = writeln!(out, "| Field | Meaning |");
            let _ = writeln!(out, "| --- | --- |");
            for field_option in &item.fields {
                let _ = writeln!(
                    out,
                    "| `{field}` | {label} |",
                    field = cell(&field_option.field),
                    label = cell(&field_option.label),
                );
            }
            let _ = writeln!(out);
        }
    }

    out
}

// --- Type presets ---------------------------------------------------------------

/// Per-language preset summaries keyed by preset id.
fn summaries_by_id(language: &str) -> BTreeMap<String, TypePresetSummary> {
    type_presets_response(Some(language))
        .presets
        .into_iter()
        .map(|summary| (summary.id.clone(), summary))
        .collect()
}

fn presets_page() -> Result<String> {
    let en = type_presets_response(Some("en"));
    let ja = summaries_by_id("ja");
    let zh_hans = summaries_by_id("zh-Hans");
    let zh_hant = summaries_by_id("zh-Hant");

    // Resolve every preset at once (empty current schema, English text) so
    // relation fields survive — exactly what onboarding does when all presets
    // are picked.
    let preset_ids: Vec<String> = en.presets.iter().map(|preset| preset.id.clone()).collect();
    let resolved = resolve_presets(&ResolveTypePresetsRequest {
        current_types: Vec::new(),
        preset_ids: preset_ids.clone(),
        language: Some("en".to_string()),
    });
    ensure!(
        resolved.collisions.is_empty(),
        "resolving all presets against an empty schema should not collide"
    );
    ensure!(
        resolved.types.len() == preset_ids.len(),
        "expected one resolved type per preset"
    );
    let configs: BTreeMap<&str, &EntityTypeConfig> = preset_ids
        .iter()
        .zip(resolved.types.iter())
        .map(|(id, config)| (id.as_str(), config))
        .collect();
    let suggestions = kizunashelf::presets::suggested_lists(&resolved.types, Some("en"));
    let suggested_lists: BTreeMap<&str, &kizunashelf::presets::SuggestedList> = suggestions
        .iter()
        .map(|section| (section.entity_type.as_str(), section))
        .collect();

    let mut out = String::new();
    front_matter(
        &mut out,
        "Type presets",
        "Every built-in type preset — its fields, roles, and provider wiring — generated from the preset registry.",
        10,
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "{BANNER}");
    let _ = writeln!(out);
    let _ = writeln!(out, "The built-in presets offered during onboarding and by **Settings → add a built-in type**, generated directly from the app — so this page always matches the version you're running. Everything a preset seeds is ordinary schema you can edit afterwards; nothing is special-cased.");
    let _ = writeln!(out);
    let _ = writeln!(out, "The tables below show each preset resolved with **English** as the picker language. Your own language choice stamps the title/filename/season languages and selects the seeded text (labels, folder names, status options, suggested list names) — the preset name is shown here in all four preset languages.");
    let _ = writeln!(out);

    for category in &en.categories {
        let _ = writeln!(out, "## {}", cell(&category.label));
        let _ = writeln!(out);
        for summary in en
            .presets
            .iter()
            .filter(|preset| preset.category == category.id)
        {
            let config = configs
                .get(summary.id.as_str())
                .with_context(|| format!("no resolved config for preset {}", summary.id))?;
            write_preset(
                &mut out,
                summary,
                config,
                &ja,
                &zh_hans,
                &zh_hant,
                &suggested_lists,
            );
        }
    }

    Ok(out)
}

fn write_preset(
    out: &mut String,
    summary: &TypePresetSummary,
    config: &EntityTypeConfig,
    ja: &BTreeMap<String, TypePresetSummary>,
    zh_hans: &BTreeMap<String, TypePresetSummary>,
    zh_hant: &BTreeMap<String, TypePresetSummary>,
    suggested_lists: &BTreeMap<&str, &kizunashelf::presets::SuggestedList>,
) {
    let _ = writeln!(out, "### {}", cell(&summary.label));
    let _ = writeln!(out);
    let localized: Vec<String> = [ja, zh_hans, zh_hant]
        .iter()
        .filter_map(|map| map.get(&summary.id))
        .map(|other| other.label.clone())
        .filter(|label| label != &summary.label)
        .collect();
    if localized.is_empty() {
        let _ = writeln!(out, "`{}` — {}", summary.id, summary.description);
    } else {
        let _ = writeln!(
            out,
            "`{}` ({}) — {}",
            summary.id,
            localized.join(" · "),
            summary.description
        );
    }
    let _ = writeln!(out);

    if !config.external_priority.is_empty() {
        let providers = config
            .external_priority
            .iter()
            .map(|id| format!("`{id}`"))
            .collect::<Vec<_>>()
            .join(" → ");
        let _ = writeln!(out, "- **Provider priority**: {providers}");
    }
    if let Some(filename) = &config.filename {
        let mut parts = Vec::new();
        if let Some(language) = &filename.title_language {
            parts.push(format!("titleLanguage `{language}`"));
        }
        if let Some(role) = &filename.title_role {
            parts.push(format!("titleRole `{}`", wire(role)));
        }
        if !parts.is_empty() {
            let _ = writeln!(out, "- **Filename**: {}", parts.join(", "));
        }
    }
    for section in &config.body_sections {
        let mut detail = wire(&section.kind);
        if !section.external_fields.is_empty() {
            let sources = section
                .external_fields
                .iter()
                .map(|mapping| format!("`{}.{}`", mapping.source, mapping.field))
                .collect::<Vec<_>>()
                .join(", ");
            detail = format!("{detail}: {sources}");
        }
        if let Some(tracking) = &section.tracking {
            detail = format!("{detail}, tracking `{}`", wire(tracking));
        }
        let _ = writeln!(
            out,
            "- **Body section** \"{}\": {detail}",
            cell(&section.heading)
        );
    }
    if let Some(log) = &config.log {
        let mut parts = Vec::new();
        if let Some(section) = &log.section {
            parts.push(format!("section \"{}\"", cell(section)));
        }
        if let Some(line_format) = &log.line_format {
            parts.push(format!("`{}`", cell(line_format)));
        }
        if !parts.is_empty() {
            let _ = writeln!(out, "- **Daily-note log**: {}", parts.join(", "));
        }
    }
    if let Some(section) = suggested_lists.get(config.id.as_str()) {
        let sort = format!(", sorted by `{}`", section.sort.property);
        let _ = writeln!(
            out,
            "- **Suggested smart list**: \"{}\"{sort}",
            cell(&section.title)
        );
    }
    let _ = writeln!(out);

    let _ = writeln!(out, "| Field | `fieldType` | Wiring | Display name |");
    let _ = writeln!(out, "| --- | --- | --- | --- |");
    for field in &config.fields {
        let _ = writeln!(
            out,
            "| `{field}` | `{field_type}` | {wiring} | {display} |",
            field = cell(&field.field),
            field_type = wire(&field.field_type),
            wiring = field_wiring(field),
            display = field.display_name.as_deref().map(cell).unwrap_or_default(),
        );
    }
    let _ = writeln!(out);
}

/// The role/wiring summary column for one preset field.
fn field_wiring(field: &FieldConfig) -> String {
    let mut notes: Vec<String> = Vec::new();
    if let Some(language) = &field.title_language {
        notes.push(format!("titleLanguage `{language}`"));
    }
    if let Some(role) = &field.title_role {
        notes.push(format!("titleRole `{}`", wire(role)));
    }
    if let Some(role) = &field.date_role {
        notes.push(format!("dateRole `{}`", wire(role)));
    }
    if let Some(language) = &field.season_language {
        notes.push(format!("seasonLanguage `{}`", wire(language)));
    }
    if let Some(role) = &field.enum_role {
        notes.push(format!("enumRole `{}`", wire(role)));
    }
    if !field.enum_options.is_empty() {
        let options = field
            .enum_options
            .iter()
            .map(|option| cell(option))
            .collect::<Vec<_>>()
            .join(" / ");
        notes.push(format!("options: {options}"));
    }
    if let Some(total) = &field.total_progress_field {
        notes.push(format!("total from `{}`", cell(total)));
    }
    if let Some(provider) = &field.external_ref {
        let types = if field.external_types.is_empty() {
            String::new()
        } else {
            format!(" (types {})", field.external_types.join(", "))
        };
        notes.push(format!("externalRef `{provider}`{types}"));
    }
    if let Some(target) = &field.relation_type {
        notes.push(format!("relation → `{target}`"));
    }
    if !field.external_fields.is_empty() {
        let sources = field
            .external_fields
            .iter()
            .map(|mapping| format!("`{}.{}`", mapping.source, mapping.field))
            .collect::<Vec<_>>()
            .join(", ");
        notes.push(format!("filled from {sources}"));
    }
    notes.join("; ")
}
