//! `kizunashelf-docs` — emits the generated reference pages of the manual
//! (`manual/content/reference/`) from the Rust source of truth: the field-type
//! and role enums (`types.rs`), the external-provider catalog (`api/external.rs`),
//! and the type-preset registry (`presets.rs`).
//!
//! CI regenerates and `git diff --exit-code`s the output, exactly like the
//! OpenAPI contract and the Lingui catalogs, so these pages can never drift
//! from the code. Regenerate with `pnpm docs:generate`.
//!
//! Enum variant lists are read back from the schemars-generated JSON schema (so
//! a new variant always appears), while the per-variant prose lives in
//! exhaustive `match`es below (so a new variant fails compilation until it is
//! described).

use anyhow::{ensure, Context, Result};
use kizunashelf::api::{provider_catalog_items, provider_episode_support};
use kizunashelf::contract::{ResolveTypePresetsRequest, TypePresetSummary};
use kizunashelf::presets::{resolve_presets, type_presets_response};
use kizunashelf::secrets::credential_env_var;
use kizunashelf::types::{
    CanonicalStatus, DateRole, EntityTypeConfig, EnumRole, FieldConfig, FieldType, SeasonLanguage,
    TitleRole,
};
use serde::de::DeserializeOwned;
use serde::Serialize;
use serde_json::Value;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

const BANNER: &str = "<!-- GENERATED by kizunashelf-docs (crates/kizunashelf/src/bin/docs.rs); do not edit by hand. Regenerate with `pnpm docs:generate`. -->";

fn main() -> Result<()> {
    let out_dir = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("manual/content/reference"));
    fs::create_dir_all(&out_dir)?;
    fs::write(out_dir.join("field-types.md"), field_types_page()?)?;
    fs::write(out_dir.join("providers.md"), providers_page())?;
    fs::write(out_dir.join("presets.md"), presets_page()?)?;
    Ok(())
}

// --- Shared helpers -------------------------------------------------------------

/// The serde wire name of a value (e.g. `FieldType::ImageList` → `imageList`).
fn wire<T: Serialize>(value: &T) -> String {
    match serde_json::to_value(value) {
        Ok(Value::String(name)) => name,
        other => unreachable!("enum should serialize to a string, got {other:?}"),
    }
}

/// Writes the Docusaurus YAML front matter every generated page starts with.
///
/// `position` becomes `sidebar_position`, which is what orders the page inside
/// the Reference category (the manual's sidebar is autogenerated from the
/// content tree).
fn front_matter(out: &mut String, title: &str, description: &str, position: u32) {
    let _ = writeln!(out, "---");
    let _ = writeln!(out, "title: \"{title}\"");
    let _ = writeln!(out, "description: \"{description}\"");
    let _ = writeln!(out, "sidebar_position: {position}");
    let _ = writeln!(out, "---");
}

/// Escapes a value for use inside a Markdown table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

/// All wire names of a flat string enum, read from its schemars schema so the
/// list can never miss a variant.
fn enum_wire_values<T: schemars::JsonSchema>() -> Result<Vec<String>> {
    let schema = serde_json::to_value(schemars::schema_for!(T))?;
    let values = schema
        .get("enum")
        .and_then(Value::as_array)
        .with_context(|| {
            format!(
                "schema for {} has no flat `enum` list",
                std::any::type_name::<T>()
            )
        })?;
    values
        .iter()
        .map(|value| {
            value
                .as_str()
                .map(str::to_string)
                .context("non-string enum value")
        })
        .collect()
}

/// `(wire name, description)` rows for a flat string enum, in declaration order.
fn enum_rows<T>(describe: fn(&T) -> &'static str) -> Result<Vec<(String, &'static str)>>
where
    T: schemars::JsonSchema + DeserializeOwned,
{
    enum_wire_values::<T>()?
        .into_iter()
        .map(|name| {
            let variant: T = serde_json::from_value(Value::String(name.clone()))?;
            Ok((name, describe(&variant)))
        })
        .collect()
}

fn enum_table(out: &mut String, header: &str, rows: &[(String, &'static str)]) {
    let _ = writeln!(out, "| {header} | Meaning |");
    let _ = writeln!(out, "| --- | --- |");
    for (name, meaning) in rows {
        let _ = writeln!(out, "| `{name}` | {meaning} |");
    }
    let _ = writeln!(out);
}

